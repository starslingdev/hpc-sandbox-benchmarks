// Prototype of the generated fleet joins in packages/drivers: DRIVERS (exists today) plus
// ARTIFACT_BUILDERS. The generator checks `./artifact` exactness against the registry: a baked
// provider must export it (unless it bakes by native snapshot, whose builder is derived from the
// driver's snapshot capability), and no other provider may.

import type { ProviderId } from "@sandbox-benchmarks/schema/provider-ids";
import { REGISTRY } from "@sandbox-benchmarks/schema/providers";
import { providerPackage } from "../../../registry/src/projections.ts";

export interface FleetEntry {
	readonly id: ProviderId;
	readonly driver: string;
	readonly artifact?: string;
}

const tsKey = (id: string) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id));

export function fleetProjection(
	ids: readonly ProviderId[],
	exportsOf: (directory: string) => Readonly<Record<string, string>>,
): { readonly entries: FleetEntry[]; readonly failures: string[] } {
	const entries: FleetEntry[] = [];
	const failures: string[] = [];
	for (const id of ids) {
		const location = providerPackage(id);
		const artifact = REGISTRY[id].artifact;
		const nativeSnapshot = "source" in artifact && artifact.source === "native-snapshot";
		const needsBuilder = artifact.kind === "baked" && !nativeSnapshot;
		const subpath = location.subpath === "." ? "./artifact" : `${location.subpath}/artifact`;
		const exported = subpath in exportsOf(location.directory);
		if (needsBuilder && !exported)
			failures.push(`${id}: baked artifact needs ${location.packageName} to export ${subpath}`);
		if (!needsBuilder && exported)
			failures.push(
				`${id}: ${location.packageName} exports ${subpath} but ${id} does not bake one`,
			);
		entries.push({
			id,
			driver: location.specifier,
			...(needsBuilder && { artifact: `${location.packageName}/${subpath.slice(2)}` }),
		});
	}
	return { entries, failures };
}

export function renderFleetJoins(entries: readonly FleetEntry[]): string {
	const drivers = entries.map(
		(entry) =>
			`\t${tsKey(entry.id)}: () => import("${entry.driver}").then((module) => module.default),`,
	);
	const builders = entries
		.filter((entry) => entry.artifact)
		.map(
			(entry) =>
				`\t${tsKey(entry.id)}: () => import("${entry.artifact}").then((module) => module.default),`,
		);
	return [
		"// GENERATED by generate-providers. Do not edit.",
		"export const DRIVERS = Object.freeze({",
		...drivers,
		"});",
		"",
		"/** Exhaustive over baked providers; loading one never evaluates any driver. */",
		"export const ARTIFACT_BUILDERS = Object.freeze({",
		...builders,
		"});",
		"",
	].join("\n");
}

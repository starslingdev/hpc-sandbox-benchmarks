import { afterAll, beforeEach, describe, expect, it } from "bun:test";
import type { FsEntry as MsbFsEntry } from "microsandbox";
import { Sandbox as MsbSandbox } from "microsandbox";
import { microsandboxCloudCompute, microsandboxFileEntries } from "./microsandbox.ts";

const sandboxStatics = MsbSandbox as unknown as {
	builder: typeof MsbSandbox.builder;
	get: typeof MsbSandbox.get;
	remove: typeof MsbSandbox.remove;
};
const stockStatics = {
	builder: sandboxStatics.builder,
	get: sandboxStatics.get,
	remove: sandboxStatics.remove,
};

let builtName = "";
let getNames: string[] = [];
let removedNames: string[] = [];
let stopCalls = 0;
let cleanupGetError: Error | undefined;
let residueStatus = "error";

function failedBuilder(name: string): ReturnType<typeof MsbSandbox.builder> {
	builtName = name;
	let builder: Record<PropertyKey, unknown>;
	builder = new Proxy(
		{},
		{
			get: (_target, property) =>
				property === "create"
					? async () => {
							throw new Error("simulated create failure");
						}
					: () => builder,
		},
	);
	return builder as unknown as ReturnType<typeof MsbSandbox.builder>;
}

function cloudProvider() {
	return microsandboxCloudCompute({
		variant: "microsandbox-cloud",
		backend: { kind: "cloud", apiKey: "offline-test-key" },
		image: "alpine:3.20",
		cpus: 1,
		memoryMib: 512,
		rootDiskMib: 8192,
		maxDurationSecs: 60,
		namePrefix: "test-cloud-",
		timeoutMs: 60_000,
	});
}

describe("Microsandbox failed-create cleanup", () => {
	beforeEach(() => {
		builtName = "";
		getNames = [];
		removedNames = [];
		stopCalls = 0;
		cleanupGetError = undefined;
		residueStatus = "error";

		sandboxStatics.builder = failedBuilder;
		sandboxStatics.get = (async (name: string) => {
			getNames.push(name);
			if (cleanupGetError) throw cleanupGetError;
			return {
				name,
				status: residueStatus,
				stop: async () => {
					stopCalls++;
				},
			} as unknown as Awaited<ReturnType<typeof MsbSandbox.get>>;
		}) as typeof MsbSandbox.get;
		sandboxStatics.remove = (async (name: string) => {
			removedNames.push(name);
		}) as typeof MsbSandbox.remove;
	});

	afterAll(() => {
		sandboxStatics.builder = stockStatics.builder;
		sandboxStatics.get = stockStatics.get;
		sandboxStatics.remove = stockStatics.remove;
	});

	it("removes the error record left by a rejected autogenerated cloud create", async () => {
		await expect(cloudProvider().sandbox.create()).rejects.toThrow(/simulated create failure/);

		expect(builtName).toStartWith("test-cloud-");
		expect(getNames).toEqual([builtName]);
		expect(removedNames).toEqual([builtName]);
		expect(stopCalls).toBe(0);
	});

	it("stops a running partial sandbox before removing its record", async () => {
		residueStatus = "running";
		await expect(cloudProvider().sandbox.create()).rejects.toThrow(/simulated create failure/);

		expect(stopCalls).toBe(1);
		expect(removedNames).toEqual([builtName]);
	});

	it("never cleans an explicitly named sandbox after a rejected create", async () => {
		await expect(cloudProvider().sandbox.create({ name: "caller-owned" })).rejects.toThrow(
			/simulated create failure/,
		);

		expect(builtName).toBe("caller-owned");
		expect(getNames).toEqual([]);
		expect(removedNames).toEqual([]);
	});

	it("preserves the create failure and reports a secondary cleanup failure", async () => {
		cleanupGetError = new Error("cleanup transport unavailable");

		await expect(cloudProvider().sandbox.create()).rejects.toThrow(
			/simulated create failure; cleanup of the partial sandbox also failed: cleanup transport unavailable/,
		);
		expect(removedNames).toEqual([]);
	});
});

describe("microsandboxFileEntries", () => {
	it("preserves whitespace and newlines while mapping structured SDK entries", () => {
		const modified = new Date("2026-07-29T12:00:00Z");
		const entries = [
			{ path: "/tmp/ spaced ", kind: "file", size: 7, mode: 0o644, modified },
			{ path: "/tmp/line\nbreak", kind: "file", size: 3, mode: 0o600, modified: null },
			{ path: "/tmp/a-dir", kind: "directory", size: 0, mode: 0o755, modified: null },
			{ path: "/tmp/a-link", kind: "symlink", size: 4, mode: 0o777, modified: null },
		] satisfies MsbFsEntry[];

		expect(microsandboxFileEntries(entries)).toEqual([
			{ name: " spaced ", type: "file", size: 7, modified },
			{ name: "line\nbreak", type: "file", size: 3 },
			{ name: "a-dir", type: "directory", size: 0 },
			{ name: "a-link", type: "file", size: 4 },
		]);
	});
});

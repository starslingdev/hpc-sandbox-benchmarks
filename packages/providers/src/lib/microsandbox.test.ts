import { afterEach, beforeEach, describe, expect, it, spyOn } from "bun:test";
import type { FsEntry as MsbFsEntry } from "microsandbox";
import { Sandbox as MsbSandbox, Snapshot as MsbSnapshot, SandboxNotFoundError } from "microsandbox";
import {
	microsandboxCloudCompute,
	microsandboxFileEntries,
	microsandboxLocalCompute,
} from "./microsandbox.ts";

let builtName = "";
let getNames: string[] = [];
let removedNames: string[] = [];
let stopCalls = 0;
let cleanupGetError: Error | undefined;
let cleanupRemoveError: Error | undefined;
let residueStatus = "error";

function failedBuilder(name: string): ReturnType<typeof MsbSandbox.builder> {
	builtName = name;
	let builder: Record<PropertyKey, unknown>;
	builder = new Proxy(
		{},
		{
			get: (_target, property) =>
				property === "create"
					? async () => {
							throw new Error("simulated create failure");
						}
					: () => builder,
		},
	);
	return builder as unknown as ReturnType<typeof MsbSandbox.builder>;
}

function cloudProvider() {
	return microsandboxCloudCompute({
		variant: "microsandbox-cloud",
		backend: { kind: "cloud", apiKey: "offline-test-key" },
		image: "alpine:3.20",
		cpus: 1,
		memoryMib: 512,
		rootDiskMib: 8192,
		namePrefix: "test-cloud-",
		timeoutMs: 60_000,
	});
}

function localProvider() {
	return microsandboxLocalCompute({
		variant: "microsandbox-local",
		backend: "local",
		image: "alpine:3.20",
		cpus: 1,
		memoryMib: 512,
		rootDiskMib: 8192,
		namePrefix: "test-local-",
		timeoutMs: 60_000,
	});
}

describe("Microsandbox failed-create cleanup", () => {
	let restoreStatics = () => {};

	beforeEach(() => {
		builtName = "";
		getNames = [];
		removedNames = [];
		stopCalls = 0;
		cleanupGetError = undefined;
		cleanupRemoveError = undefined;
		residueStatus = "error";

		const builder = spyOn(MsbSandbox, "builder").mockImplementation(failedBuilder);
		const get = spyOn(MsbSandbox, "get").mockImplementation((async (name: string) => {
			getNames.push(name);
			if (cleanupGetError) throw cleanupGetError;
			return {
				name,
				status: residueStatus,
				stop: async () => {
					stopCalls++;
				},
			} as unknown as Awaited<ReturnType<typeof MsbSandbox.get>>;
		}) as typeof MsbSandbox.get);
		const remove = spyOn(MsbSandbox, "remove").mockImplementation((async (name: string) => {
			removedNames.push(name);
			if (cleanupRemoveError) throw cleanupRemoveError;
		}) as typeof MsbSandbox.remove);
		restoreStatics = () => {
			builder.mockRestore();
			get.mockRestore();
			remove.mockRestore();
		};
	});

	afterEach(() => restoreStatics());

	it("removes the error record left by a rejected autogenerated cloud create", async () => {
		await expect(cloudProvider().sandbox.create()).rejects.toThrow(/simulated create failure/);

		expect(builtName).toStartWith("test-cloud-");
		expect(getNames).toEqual([builtName]);
		expect(removedNames).toEqual([builtName]);
		expect(stopCalls).toBe(0);
	});

	it("stops a running partial sandbox before removing its record", async () => {
		residueStatus = "running";
		await expect(cloudProvider().sandbox.create()).rejects.toThrow(/simulated create failure/);

		expect(stopCalls).toBe(1);
		expect(removedNames).toEqual([builtName]);
	});

	it("never cleans an explicitly named sandbox after a rejected create", async () => {
		await expect(cloudProvider().sandbox.create({ name: "caller-owned" })).rejects.toThrow(
			/simulated create failure/,
		);

		expect(builtName).toBe("caller-owned");
		expect(getNames).toEqual([]);
		expect(removedNames).toEqual([]);
	});

	it("preserves the create failure and reports a secondary cleanup failure", async () => {
		cleanupGetError = new Error("cleanup transport unavailable");

		await expect(cloudProvider().sandbox.create()).rejects.toThrow(
			/simulated create failure; cleanup of the partial sandbox also failed: cleanup transport unavailable/,
		);
		expect(removedNames).toEqual([]);
	});

	it("treats a record removed concurrently during cleanup as already clean", async () => {
		cleanupRemoveError = new SandboxNotFoundError("sandbox disappeared");

		await expect(cloudProvider().sandbox.create()).rejects.toThrow(
			/^Failed to create .*simulated create failure$/,
		);
		expect(removedNames).toEqual([builtName]);
	});
});

describe("Microsandbox provider edge cases", () => {
	let restores: Array<() => void> = [];

	afterEach(() => {
		for (const restore of restores.reverse()) restore();
		restores = [];
	});

	function restore<T extends { mockRestore(): void }>(spy: T): T {
		restores.push(() => spy.mockRestore());
		return spy;
	}

	it("uses the per-create timeout as the native sandbox lifetime", async () => {
		let maxDurationSecs = 0;
		let builder: Record<PropertyKey, unknown>;
		builder = new Proxy(
			{},
			{
				get: (_target, property) => {
					if (property === "maxDuration") {
						return (seconds: number) => {
							maxDurationSecs = seconds;
							return builder;
						};
					}
					if (property === "create") return async () => ({});
					return () => builder;
				},
			},
		);
		restore(
			spyOn(MsbSandbox, "builder").mockImplementation(
				(() => builder) as unknown as typeof MsbSandbox.builder,
			),
		);
		restore(
			spyOn(MsbSandbox, "get").mockImplementation(
				(async (name: string) =>
					({
						name,
						status: "running",
						configJson: "{}",
						createdAt: new Date("2026-07-30T00:00:00Z"),
					}) as unknown as Awaited<ReturnType<typeof MsbSandbox.get>>) as typeof MsbSandbox.get,
			),
		);

		const sandbox = await cloudProvider().sandbox.create({ timeout: 12_345 });

		expect(maxDurationSecs).toBe(13);
		expect((await sandbox.getInfo()).timeout).toBe(12_345);
	});

	it("does not replay a command after an ambiguous agent failure", async () => {
		let execCalls = 0;
		const nativeSandbox = {
			execWith: async () => {
				execCalls++;
				throw new Error("connection closed after acceptance");
			},
		};
		let builder: Record<PropertyKey, unknown>;
		builder = new Proxy(
			{},
			{
				get: (_target, property) =>
					property === "create" ? async () => nativeSandbox : () => builder,
			},
		);
		restore(
			spyOn(MsbSandbox, "builder").mockImplementation(
				(() => builder) as unknown as typeof MsbSandbox.builder,
			),
		);

		const sandbox = await cloudProvider().sandbox.create();
		const result = await sandbox.runCommand("touch /tmp/must-run-once");

		expect(result.exitCode).toBe(127);
		expect(result.stderr).toBe("connection closed after acceptance");
		expect(execCalls).toBe(1);
	});

	it("surfaces parent mkdir failure before attempting a file write", async () => {
		let writes = 0;
		const nativeSandbox = {
			execWith: async () => ({
				stdout: () => "",
				stderr: () => "read-only filesystem",
				code: 1,
			}),
			fs: () => ({
				write: async () => {
					writes++;
				},
			}),
		};
		let builder: Record<PropertyKey, unknown>;
		builder = new Proxy(
			{},
			{
				get: (_target, property) =>
					property === "create" ? async () => nativeSandbox : () => builder,
			},
		);
		restore(
			spyOn(MsbSandbox, "builder").mockImplementation(
				(() => builder) as unknown as typeof MsbSandbox.builder,
			),
		);

		const sandbox = await cloudProvider().sandbox.create();

		await expect(sandbox.filesystem.writeFile("/locked/result.json", "{}")).rejects.toThrow(
			"mkdir failed for /locked: read-only filesystem",
		);
		expect(writes).toBe(0);
	});

	it("reconnects once for an idempotent filesystem operation on a stale agent", async () => {
		let reads = 0;
		const staleSandbox = {
			fs: () => ({
				readToString: async () => {
					reads++;
					throw new Error("stale agent");
				},
			}),
		};
		const freshSandbox = {
			fs: () => ({
				readToString: async () => {
					reads++;
					return "recovered";
				},
			}),
		};
		let builder: Record<PropertyKey, unknown>;
		builder = new Proxy(
			{},
			{
				get: (_target, property) =>
					property === "create" ? async () => staleSandbox : () => builder,
			},
		);
		restore(
			spyOn(MsbSandbox, "builder").mockImplementation(
				(() => builder) as unknown as typeof MsbSandbox.builder,
			),
		);
		restore(
			spyOn(MsbSandbox, "get").mockImplementation(
				(async (name: string) =>
					({
						name,
						status: "running",
						connect: async () => freshSandbox,
					}) as unknown as Awaited<ReturnType<typeof MsbSandbox.get>>) as typeof MsbSandbox.get,
			),
		);

		const sandbox = await cloudProvider().sandbox.create();

		expect(await sandbox.filesystem.readFile("/tmp/result")).toBe("recovered");
		expect(reads).toBe(2);
	});

	it("lists legacy prefix-owned sandboxes without requiring the current label", async () => {
		let labelCalls = 0;
		restore(
			spyOn(MsbSandbox, "listWith").mockImplementation((async (
				configure: Parameters<typeof MsbSandbox.listWith>[0],
			) => {
				let listBuilder: Record<PropertyKey, unknown>;
				listBuilder = new Proxy(
					{},
					{
						get: (_target, property) => {
							if (property === "label") {
								return () => {
									labelCalls++;
									return listBuilder;
								};
							}
							return () => listBuilder;
						},
					},
				);
				configure(listBuilder as never);
				return {
					sandboxes: [
						{
							name: "test-cloud-legacy",
							status: "stopped",
							configJson: "{}",
							createdAt: new Date("2026-07-30T00:00:00Z"),
						},
						{
							name: "somebody-else",
							status: "stopped",
							configJson: "{}",
							createdAt: new Date("2026-07-30T00:00:00Z"),
						},
					],
					nextCursor: null,
				};
			}) as unknown as typeof MsbSandbox.listWith),
		);

		const listed = await cloudProvider().sandbox.list();

		expect(listed.map((sandbox) => sandbox.sandboxId)).toEqual(["test-cloud-legacy"]);
		expect(labelCalls).toBe(0);
	});

	it("reports both snapshot and restart failures", async () => {
		let getCalls = 0;
		restore(
			spyOn(MsbSandbox, "get").mockImplementation((async (name: string) => {
				getCalls++;
				return {
					name,
					status: "running",
					stop: async () => {},
					startDetached: async () => {
						throw new Error("restart unavailable");
					},
				} as unknown as Awaited<ReturnType<typeof MsbSandbox.get>>;
			}) as typeof MsbSandbox.get),
		);
		let snapshotBuilder: Record<PropertyKey, unknown>;
		snapshotBuilder = new Proxy(
			{},
			{
				get: (_target, property) =>
					property === "create"
						? async () => {
								throw new Error("snapshot unavailable");
							}
						: () => snapshotBuilder,
			},
		);
		restore(
			spyOn(MsbSnapshot, "builder").mockImplementation(
				(() => snapshotBuilder) as unknown as typeof MsbSnapshot.builder,
			),
		);

		const error = await localProvider()
			.snapshot?.create("sandbox-1", { name: "snapshot-1" })
			.catch((caught) => caught);

		expect(error).toBeInstanceOf(AggregateError);
		expect(error.message).toContain(
			"snapshot unavailable; restart also failed: restart unavailable",
		);
		expect(error.errors.map((entry: unknown) => String(entry))).toEqual([
			"Error: snapshot unavailable",
			"Error: restart unavailable",
		]);
		expect(getCalls).toBe(2);
	});
});

describe("microsandboxFileEntries", () => {
	it("preserves whitespace and newlines while mapping structured SDK entries", () => {
		const modified = new Date("2026-07-29T12:00:00Z");
		const entries = [
			{ path: "/tmp/ spaced ", kind: "file", size: 7, mode: 0o644, modified },
			{ path: "/tmp/line\nbreak", kind: "file", size: 3, mode: 0o600, modified: null },
			{ path: "/tmp/a-dir", kind: "directory", size: 0, mode: 0o755, modified: null },
			{ path: "/tmp/a-link", kind: "symlink", size: 4, mode: 0o777, modified: null },
		] satisfies MsbFsEntry[];

		expect(microsandboxFileEntries(entries)).toEqual([
			{ name: " spaced ", type: "file", size: 7, modified },
			{ name: "line\nbreak", type: "file", size: 3 },
			{ name: "a-dir", type: "directory", size: 0 },
			{ name: "a-link", type: "file", size: 4 },
		]);
	});
});

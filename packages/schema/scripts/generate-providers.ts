#!/usr/bin/env bun
// `generate-providers`: the one generator for everything derived from provider metadata (ADR-0006,
// ADR-0023). It validates the hand-authored descriptor modules, renders the correlated registry
// assembly from the dependency-free identity tuple, then renders the wiring that projects the
// registry into workflows, docs, env examples, provenance and the driver loader.
//
// `--check` renders the same files and fails when any committed byte differs, which is the drift
// check CI runs. Comparing content rather than `git diff` also catches a
// newly created, still-untracked output.
//
// The wiring renderers import the generated registry, so they are loaded only after the registry
// assembly has been rendered: a freshly added provider id is assembled before anything reads it.
import { readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { PROVIDER_IDS } from "../src/provider-ids.ts";
import { validateProviderModules } from "./provider-meta-schema.ts";

const SCHEMA_ROOT = resolve(import.meta.dir, "..");
export const REPO_ROOT = resolve(SCHEMA_ROOT, "../..");
const REGISTRY_FILE = relative(REPO_ROOT, resolve(SCHEMA_ROOT, "src/provider-meta/index.ts"));

function identifier(id: string): string {
	return id.replaceAll("-", "_");
}

const isIdentifier = (id: string): boolean => /^[A-Za-z_$][\w$]*$/.test(id);

function propertyKey(id: string): string {
	return isIdentifier(id) ? id : JSON.stringify(id);
}

function propertyAccess(id: string): string {
	return isIdentifier(id) ? `.${id}` : `[${JSON.stringify(id)}]`;
}

/** The correlated assembly that makes a missing, extra or wrongly declared module a compile error. */
export function renderProviderRegistry(): string {
	const imports = [...PROVIDER_IDS]
		.sort((left, right) => left.localeCompare(right))
		.map((id) => `import ${identifier(id)} from ${JSON.stringify(`./${id}.ts`)};`);
	const modules = PROVIDER_IDS.map((id) => `\t${propertyKey(id)}: ${identifier(id)},`);
	const registry = PROVIDER_IDS.map(
		(id) => `\t${propertyKey(id)}: MODULES${propertyAccess(id)}.meta,`,
	);

	return [
		"// GENERATED by packages/schema/scripts/generate-providers.ts. Edit provider files or PROVIDER_IDS, then regenerate.",
		'import type { ProviderId } from "../provider-ids.ts";',
		'import type { ProviderArtifact, ProviderMetaModule, ProviderMetaSource } from "../provider-meta.ts";',
		...imports,
		"",
		"const MODULES = {",
		...modules,
		"} as const satisfies { [P in ProviderId]: ProviderMetaModule<P> };",
		"",
		"export const REGISTRY = {",
		...registry,
		"} as const satisfies Record<ProviderId, ProviderMetaSource>;",
		"",
		'type IdsWithArtifact<K extends ProviderArtifact["kind"]> = {',
		'\t[P in ProviderId]: (typeof REGISTRY)[P]["artifact"]["kind"] extends K ? P : never;',
		"}[ProviderId];",
		"",
		'export type BakedProviderId = IdsWithArtifact<"baked">;',
		'export type ImageProviderId = IdsWithArtifact<"image">;',
		'export type MirroredProviderId = IdsWithArtifact<"mirror">;',
		'export type BuiltProviderId = IdsWithArtifact<"built">;',
		'export type StockProviderId = IdsWithArtifact<"none">;',
		"",
	].join("\n");
}

/** Import every descriptor module by id, without going through the generated assembly. */
async function loadProviderModules(): Promise<Record<(typeof PROVIDER_IDS)[number], unknown>> {
	const entries = await Promise.all(
		PROVIDER_IDS.map(async (id) => {
			const url = new URL(`../src/provider-meta/${id}.ts`, import.meta.url);
			const loaded = (await import(url.href)) as { default?: unknown };
			return [id, loaded.default] as const;
		}),
	);
	return Object.fromEntries(entries) as Record<(typeof PROVIDER_IDS)[number], unknown>;
}

async function renderWiring(): Promise<Map<string, string>> {
	const { renderProviderWiringFiles } = await import("./provider-wiring.ts");
	return renderProviderWiringFiles(REPO_ROOT);
}

/** Validate the metadata, then write the registry assembly followed by every wiring output. */
export async function generateProviders(): Promise<number> {
	validateProviderModules(await loadProviderModules());
	await Bun.write(resolve(REPO_ROOT, REGISTRY_FILE), renderProviderRegistry());
	const wiring = await renderWiring();
	for (const [file, content] of wiring) await Bun.write(resolve(REPO_ROOT, file), content);
	return wiring.size + 1;
}

/** Validate the metadata and name every committed output a fresh generation would change. */
export async function driftedProviderFiles(): Promise<string[]> {
	validateProviderModules(await loadProviderModules());
	const current = (file: string): string => readFileSync(resolve(REPO_ROOT, file), "utf8");
	if (current(REGISTRY_FILE) !== renderProviderRegistry()) {
		// The wiring would render against the stale assembly; the registry is the whole answer.
		return [REGISTRY_FILE];
	}
	return [...(await renderWiring())]
		.filter(([file, expected]) => current(file) !== expected)
		.map(([file]) => file);
}

if (import.meta.main) {
	const check = process.argv.includes("--check");
	try {
		if (check) {
			const drifted = await driftedProviderFiles();
			if (drifted.length > 0) {
				console.error(
					`generated provider files drifted: ${drifted.join(", ")}; run \`bun run generate-providers\` and commit the result`,
				);
				process.exit(1);
			}
			console.log("✓ generated provider files match the metadata registry");
		} else {
			const written = await generateProviders();
			console.log(`✓ ${PROVIDER_IDS.length} providers -> ${written} generated files`);
		}
	} catch (error) {
		console.error(`generate-providers${check ? " --check" : ""} failed:`, error);
		process.exit(1);
	}
}

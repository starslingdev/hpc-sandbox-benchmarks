#!/usr/bin/env bun
// Generate the correlated provider metadata assembly from the dependency-free identity tuple.
// Provider files remain hand-authored; this is the reviewed mechanical join that makes a missing,
// extra, or wrongly-declared module fail compilation without giving filesystem discovery ownership
// of provider identity (ADR-0006).
import { PROVIDER_IDS } from "../src/provider-ids.ts";
import { validateProviderModules } from "./provider-meta-schema.ts";

const OUT_FILE = `${import.meta.dir}/../src/provider-meta/index.ts`;

function identifier(id: string): string {
	return id.replaceAll("-", "_");
}

function propertyAccess(id: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(id) ? `.${id}` : `[${JSON.stringify(id)}]`;
}

export function renderProviderRegistry(): string {
	const imports = PROVIDER_IDS.map(
		(id) => `import ${identifier(id)} from ${JSON.stringify(`./${id}.ts`)};`,
	);
	const modules = PROVIDER_IDS.map((id) => `\t${JSON.stringify(id)}: ${identifier(id)},`);
	const registry = PROVIDER_IDS.map(
		(id) => `\t${JSON.stringify(id)}: MODULES${propertyAccess(id)}.meta,`,
	);

	return [
		"// GENERATED by scripts/generate-provider-registry.ts. Edit provider files or PROVIDER_IDS, then regenerate.",
		'import type { ProviderId } from "../provider-ids.ts";',
		'import type { ProviderArtifact, ProviderMetaModule, ProviderMetaSource } from "../provider-meta.ts";',
		...imports,
		"",
		"const MODULES = {",
		...modules,
		"} as const satisfies { [P in ProviderId]: ProviderMetaModule<P> };",
		"",
		"export const REGISTRY = {",
		...registry,
		"} as const satisfies Record<ProviderId, ProviderMetaSource>;",
		"",
		'type IdsWithArtifact<K extends ProviderArtifact["kind"]> = {',
		'\t[P in ProviderId]: (typeof REGISTRY)[P]["artifact"]["kind"] extends K ? P : never;',
		"}[ProviderId];",
		"",
		'export type BakedProviderId = IdsWithArtifact<"baked">;',
		'export type ImageProviderId = IdsWithArtifact<"image">;',
		'export type MirroredProviderId = IdsWithArtifact<"mirror">;',
		'export type BuiltProviderId = IdsWithArtifact<"built">;',
		'export type StockProviderId = IdsWithArtifact<"none">;',
		"",
	].join("\n");
}

async function loadProviderModules(): Promise<Record<(typeof PROVIDER_IDS)[number], unknown>> {
	const entries = await Promise.all(
		PROVIDER_IDS.map(async (id) => {
			const url = new URL(`../src/provider-meta/${id}.ts`, import.meta.url);
			const loaded = (await import(url.href)) as { default?: unknown };
			return [id, loaded.default] as const;
		}),
	);
	return Object.fromEntries(entries) as Record<(typeof PROVIDER_IDS)[number], unknown>;
}

export async function generateProviderRegistryFile(): Promise<void> {
	// Validate module correlation and every descriptor invariant before touching generated output.
	validateProviderModules(await loadProviderModules());
	await Bun.write(OUT_FILE, renderProviderRegistry());
	const format = Bun.spawn(["bunx", "biome", "check", "--write", OUT_FILE], {
		stdout: "inherit",
		stderr: "inherit",
	});
	if ((await format.exited) !== 0) {
		throw new Error("biome check failed on generated provider registry");
	}
	console.log(`✓ ${PROVIDER_IDS.length} providers -> src/provider-meta/index.ts`);
}

if (import.meta.main) {
	try {
		await generateProviderRegistryFile();
	} catch (error) {
		console.error("generate-provider-registry failed:", error);
		process.exit(1);
	}
}
